import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {extractAdminState} from '../mirpanel-admin/core.mjs';
import {generateProductPageFiles,generateRedirects} from '../mirpanel-admin/product-pages.mjs';
import {productCustomerContent} from '../product-seo-content.mjs';
const source=fs.readFileSync('app.js','utf8'),state=extractAdminState(source);
const baseline=execFileSync('git',['-c','safe.directory='+process.cwd().replaceAll('\\','/'),'show','1001689:app.js'],{encoding:'utf8',maxBuffer:8e6});
const before=extractAdminState(baseline);
const commerce=p=>Object.fromEntries(Object.entries(p).filter(([k])=>!k.startsWith('seo')&&!['imageAlt','longDescription','desc',...(p.id==='chatgpt'?['note']:[])].includes(k)));
const rawData=s=>JSON.parse(s.match(/const DATA\s*=\s*({[\s\S]*?\n});/)[1]);
assert.deepEqual(rawData(source).products.map(commerce),rawData(baseline).products.map(commerce),'No price, stock, package, supplier, flow, activation or private-guide changes');
for(const key of ['categories','siteSections','ui','cms','phone_wa'])assert.equal(JSON.stringify(state[key]),JSON.stringify(before[key]),key+' unchanged');
assert.equal(state.products.length,36);
const titles=new Set(),descriptions=new Set(),pages=generateProductPageFiles(state.products,state.siteSections,state.cms,state.content);
for(const p of state.products){
 assert(p.seoTitle&&p.seoDescription&&p.seoH1&&p.imageAlt,p.id+' complete metadata');
 assert(!titles.has(p.seoTitle)&&!descriptions.has(p.seoDescription),p.id+' unique metadata');titles.add(p.seoTitle);descriptions.add(p.seoDescription);
 assert.equal(state.content[p.id].rulesHtml,productCustomerContent(p).rulesHtml,p.id+' current factual rules');
 if(p.active===false)continue;
 const html=pages.get('mehsul/'+p.seoSlug+'.page');assert(html,p.id+' generated');
 assert.equal((html.match(/<h1\b/g)||[]).length,1,p.id+' one H1');
 assert(html.includes('href="https://mirpanel.com/mehsul/'+p.seoSlug+'"'),p.id+' canonical');
 assert(html.includes(p.seoTitle.replaceAll('&','&amp;')),p.id+' title in first HTML');
 assert(html.includes('data-product-panel="rules" hidden>'),p.id+' accessible rules tab');
 assert(html.includes('Sifarişlərim')&&html.includes('href="/elaqe"'),p.id+' delivery/support links');
 const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
 const schema=graph.find(n=>n['@type']==='Product');
 assert(!schema.aggregateRating&&!schema.review,p.id+' no fabricated reviews');
 const plans=p.plans.filter(x=>x.active!==false&&Number(x.price)>0);
 assert.equal(JSON.stringify(schema.offers.map(o=>o.price)),JSON.stringify(plans.map(x=>Number(x.price).toFixed(2))),p.id+' exact offer prices');
 assert(schema.offers.every(o=>o.priceCurrency==='AZN'),p.id+' AZN');
 for(const o of schema.offers)assert(o.availability!=='https://schema.org/InStock',p.id+' no fabricated live availability in static HTML');
 assert.equal(html.includes('noindex, follow'),p.seoIndex===false,p.id+' index policy preserved');
}
const sitemap=fs.readFileSync('sitemap.xml','utf8');
for(const p of state.products)assert.equal(sitemap.includes('https://mirpanel.com/mehsul/'+p.seoSlug+'</loc>'),p.active!==false&&p.seoIndex!==false,p.id+' sitemap');
assert.equal(state.products.find(p=>p.id==='telegram_premium').seoIndex,false);
assert(generateRedirects(state.products,state.siteSections).includes('/mehsul/epinby-3436 /mehsul/pubg-mobile?plan=0 301'));
console.log(JSON.stringify({products:state.products.length,active:pages.size,uniqueMetadata:true,commerceAndPrivateGuidesUnchanged:true,schemaAndSitemap:true}));
