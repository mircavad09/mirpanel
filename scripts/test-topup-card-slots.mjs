 const cards=Array.from({length:4},id),banks=['Kapital Bank','ABB','LeoBank','m10'];
 for(let i=0;i<4;i++)await pool.query(`insert into public.payment_methods(id,stable_code,display_name,provider_name,method_type,last4,encrypted_number,sort_order,daily_limit,limit_mode,active) values($1,$2,$3,$3,'bank_card','1234','test-encrypted',$4,5,'limited',true)`,[cards[i],'test-'+i,banks[i],i+1]);
 const legacy=id();await pool.query("insert into wallet_topups(id,user_id,request_id,requested_cents,method_id,status) values($1,'a',$2,500,$3,'rejected')",[legacy,id(),cards[0]]);
