 await pool.query("update wallet_topups set reserved_until=clock_timestamp()-interval '1 minute' where id=$1",[expired.id]);
 await assert.rejects(shop.receiptTarget(req,null,'topup',expired.id),{code:'TOPUP_CARD_EXPIRED'});
