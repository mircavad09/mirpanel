 assert.deepEqual([approved.requested_cents,approved.approved_cents,approved.card_bank,approved.card_last4],['600','700','Kapital Bank','1234']);
 assert.equal(topups.find(x=>x.id===legacy).card_bank,null);
 assert.equal(Object.hasOwn(approved,'card_snapshot'),false);
