import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {extractAdminState,patchAppSource} from '../mirpanel-admin/core.mjs';
import {generateProductPageFiles,generateSitemap,generateProductPageHtml} from '../mirpanel-admin/product-pages.mjs';
import {productSeoCopy} from '../product-seo-content.mjs';
const source=fs.readFileSync('app.js','utf8'),state=extractAdminState(source);
const active=state.products.filter(p=>p.active!==false);
const pages=generateProductPageFiles(state.products,state.siteSections,state.cms,state.content);
assert.equal(pages.size,active.length);
const titles=new Set(),descriptions=new Set();
for(const p of active){
 const html=pages.get('mehsul/'+p.seoSlug+'.page');
 assert(html);
 assert.equal((html.match(/<h1\b/g)||[]).length,1);
 assert.equal((html.match(/rel="canonical"/g)||[]).length,1);
 assert(html.includes('https://mirpanel.com/mehsul/'+p.seoSlug));
 assert(html.includes('İndi al'));
 assert(html.includes('Giriş və təhvil qaydası'));
 assert(html.includes('Paket zəmanəti və istifadə şərtləri'));
 assert(html.includes(productSeoCopy(p).answer));
 assert(!/WhatsApp avtomatik|WhatsApp sifariş axını|WhatsApp üzərindən tamamlanır/.test(html));
 const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
 for(const type of ['Product','BreadcrumbList','Organization'])assert.equal(graph.filter(s=>s['@type']===type).length,1);
 const prod=graph.find(s=>s['@type']==='Product');
 assert(!prod.brand&&!prod.aggregateRating&&!prod.review);
 const plans=p.plans.filter(x=>x.active!==false&&Number(x.price)>0);
 assert.equal(prod.offers.length,plans.length);
 plans.forEach((plan,i)=>{assert.equal(prod.offers[i].price,Number(plan.price).toFixed(2));assert.equal(prod.offers[i].priceCurrency,'AZN');assert.notEqual(prod.offers[i].availability,'https://schema.org/InStock');});
 assert(p.seoDescription.length>90&&p.seoContent.length>90);
 titles.add(p.seoTitle);descriptions.add(p.seoDescription);
}
assert.equal(titles.size,active.length);assert.equal(descriptions.size,active.length);
const sitemap=generateSitemap(state.products,state.siteSections,new Date(),state.cms);
assert.equal((sitemap.match(/<loc>/g)||[]).length,active.filter(p=>p.seoIndex!==false&&p.includeInSitemap!==false).length+5);
const later=generateSitemap(state.products,state.siteSections,new Date(Date.now()+86400000),state.cms);
assert.equal(sitemap,later,'Build date must not change lastmod');
const fixture=structuredClone(active[0]);fixture.seoIndex=false;fixture.plans.push({label:'Hidden',active:false,price:123});
const html=generateProductPageHtml(fixture,fixture.seoSlug,[]);
assert(html.includes('noindex, follow'));
assert(!html.includes('"price":"123.00"'));
const original=extractAdminState(execFileSync('git',['show','HEAD:app.js'],{encoding:'utf8',maxBuffer:8e6}));
const strip=p=>Object.fromEntries(Object.entries(p).filter(([k])=>!k.startsWith('seo')&&!['imageAlt','longDescription','includeInSitemap'].includes(k)));
assert.deepEqual(JSON.parse(JSON.stringify(state.products.map(strip))),JSON.parse(JSON.stringify(original.products.map(strip))),'Commerce fields unchanged');
const telegram=state.products.find(p=>p.id==='telegram_premium');
assert.equal(telegram.active,true);
assert.equal(telegram.seoIndex,false);
assert.equal(telegram.includeInSitemap,false);
assert(pages.get('mehsul/telegram-premium.page').includes('content="noindex, follow"'));
assert(!sitemap.includes('/mehsul/telegram-premium'));
for(const p of active)assert.equal(state.content[p.id]?.rulesHtml||'',original.content[p.id]?.rulesHtml||'','Usage rules unchanged');
const changed=structuredClone(state);changed.products[0].plans[0].price+=1;
const captured=extractAdminState(patchAppSource(source,changed));
assert(Date.parse(captured.products[0].seoUpdatedAt)>Date.parse(state.products[0].seoUpdatedAt));
const edge=fs.readFileSync('functions/_middleware.js','utf8');
assert(!edge.includes('new Response(MARKDOWN'));
console.log(JSON.stringify({activeProducts:active.length,uniqueMetadata:true,initialHtml:true,oneH1:true,canonical:true,accurateOffers:true,privateNoindex:true,stableLastmod:true,commerceUnchanged:true}));
